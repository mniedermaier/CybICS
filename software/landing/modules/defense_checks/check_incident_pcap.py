"""
Challenge check: the student reconstructed the incident from a capture (incident_pcap).

The challenge hands out training/incident_pcap/incident.pcap, two minutes from
the mirror port of the PLC's switch port. A rogue device (a Raspberry Pi)
joins the plant network, sweeps it with ARP, port-scans the PLC, poisons the
PLC's ARP cache for the HMI (172.18.0.4) and the engineering workstation
(172.18.0.10) and then stops the plant three times: a Modbus write from the
HMI's address, an S7comm Write Var from the workstation's address and a DNP3
Direct Operate from its own address. The operator restarts the plant from
the real HMI after each stop.

The student answers four questions out of the capture: the rogue device's
MAC, every IP address it used or impersonated, the number of the first frame
in which it claims another host's address, and the numbers of the three
frames that carry a stop command. Grading is all or nothing (grade()'s
default), so a partly right timeline cannot be completed by trying one field
at a time. The module does not touch the stack.

The capture is generated by software/scripts/generate_incident_pcap.py. The
expected values below are that script's answer key; tests/test_incident_pcap.py
regenerates the capture, compares it with the committed file and derives
these answers from the bytes again, so the file and this module cannot drift.
"""
import re

from modules.defense_checks._answers import grade, number

ATTACKER_MAC = "b8:27:eb:3c:9a:71"
ATTACKER_IPS = frozenset({"172.18.0.77", "172.18.0.4", "172.18.0.10"})
POISON_FRAME = 293
STOP_FRAMES = frozenset({345, 553, 736})     # Modbus, S7comm, DNP3

LABELS = {
    "attacker_mac": "MAC address of the rogue device",
    "attacker_ips": "IP addresses the rogue device used or impersonated",
    "poison_frame": "First frame in which it claims another host's IP address",
    "stop_frames": "Frames that carry the three stop commands",
}

_SEPARATORS = re.compile(r"[\s,;]+")


def mac(expected):
    """Accept a MAC as aa:bb:cc:dd:ee:ff, aa-bb-..., aabb.ccdd.eeff or 12 hex digits."""
    want = re.sub(r"[^0-9a-f]", "", expected.lower())

    def check(value):
        text = str(value).strip().lower()
        if not re.fullmatch(r"[0-9a-f:.\-]+", text):
            return False
        return re.sub(r"[^0-9a-f]", "", text) == want
    return check


def same_set(expected, item=str):
    """Accept a list separated by commas, semicolons or spaces, in any order, no extras."""
    want = frozenset(expected)

    def check(value):
        parts = [p for p in _SEPARATORS.split(str(value).strip()) if p]
        try:
            got = [item(p) for p in parts]
        except ValueError:
            return False
        return len(got) == len(set(got)) and frozenset(got) == want
    return check


def _ip(text):
    if not re.fullmatch(r"\d{1,3}(\.\d{1,3}){3}", text):
        raise ValueError(text)
    return ".".join(str(int(octet)) for octet in text.split("."))


def _frame(text):
    text = text.lstrip("#")
    if not text.isdigit():
        raise ValueError(text)
    return int(text)


def verify(answers=None):
    return grade(answers, {
        "attacker_mac": mac(ATTACKER_MAC),
        "attacker_ips": same_set(ATTACKER_IPS, _ip),
        "poison_frame": number(POISON_FRAME),
        "stop_frames": same_set(STOP_FRAMES, _frame),
    }, labels=LABELS,
        success_message="Your timeline matches the incident. The addresses lied; "
                        "the Ethernet layer told you who was really talking.",
        failure_message="At least one answer does not match the capture yet.")
