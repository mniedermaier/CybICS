"""
Challenge check: the student caught a forged sensor with the plant's physics (physics_forensics).

The challenge hands out training/physics_forensics/historian.csv, a historian
export of one night: one row per process cycle with the pressures, the
sensors, the stop flag and the coils as the PLC held them. Near the end an
adversary in the middle rewrites the HPT pressure on its way from the I/O
service to the PLC, holding it in the working range so the compressor never
switches off. The export ends while that is still going on.

The student answers three questions: which recorded value is forged, the time
stamp of the first row the plant cannot have produced, and the real HPT
pressure in the last row (the mass balance: every 2 bar that left the GST
while the refill was off arrived as 1 bar in the HPT). Grading is all or
nothing (grade()'s default). The module does not touch the stack.

The CSV is generated by software/scripts/generate_physics_historian.py. The
expected values below are that script's answer key; tests/test_physics_forensics.py
regenerates the file, compares it with the committed one and derives these
answers from the CSV alone, so the file and this module cannot drift.
"""
import re

from modules.defense_checks._answers import grade, number, normalize

# The forged value may be named by its column, its tank or its register, in
# any combination of these words ("hpt", "HPT (HR 1126)", "high-pressure tank",
# "%MW102"). A word outside this list, such as another column, fails.
FORGED_WORDS = frozenset({"hpt", "high", "pressure", "tank", "value", "column", "the",
                          "hr", "holding", "register", "1126", "hr1126", "%mw102", "mw102", "41127"})
FORGED_IDS = frozenset({"hpt", "1126", "hr1126", "%mw102", "mw102", "41127"})
FIRST_FORGED = "2026-03-21 02:19:22.6"
TRUE_HPT_LAST_ROW = 147

LABELS = {
    "forged_value": "Recorded value that was forged",
    "first_forged": "Time stamp of the first row the plant cannot have produced",
    "true_hpt": "Real HPT pressure in the last row of the export (bar)",
}

_TIME = re.compile(r"(?:(\d{4}-\d{2}-\d{2})[ t])?(\d{1,2}):(\d{2}):(\d{2})(?:\.(\d))?z?")


def time_stamp(expected):
    """Accept the row's time as in the file, with or without the date and the tenth."""
    date, hh, mm, ss, tenth = _TIME.fullmatch(expected.lower()).groups()

    def check(value):
        m = _TIME.fullmatch(normalize(value))
        if not m:
            return False
        d, h, mi, s, t = m.groups()
        if (int(h), int(mi), int(s)) != (int(hh), int(mm), int(ss)):
            return False
        if d is not None and d != date:
            return False
        return t is None or t == tenth
    return check


def forged_value(value):
    words = re.findall(r"%?[a-z0-9]+", normalize(value))
    if not words or not set(words) <= FORGED_WORDS:
        return False
    return bool(FORGED_IDS & set(words)) or {"high", "tank"} <= set(words)


def verify(answers=None):
    return grade(answers, {
        "forged_value": forged_value,
        "first_forged": time_stamp(FIRST_FORGED),
        "true_hpt": number(TRUE_HPT_LAST_ROW),
    }, labels=LABELS,
        success_message="The gauge on the screen said 82 bar. The gas that left the storage "
                        "tank says otherwise: physics was the witness the attacker could not forge.",
        failure_message="At least one answer does not match the export yet.")
