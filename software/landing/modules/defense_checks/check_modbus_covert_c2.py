"""
Challenge check: the student found a covert channel in Modbus reads (modbus_covert_c2).

The challenge hands out training/modbus_covert_c2/baseline.pcap, four minutes
of Modbus/TCP at the PLC's mirror port, recorded to learn who reads what
before a read allowlist is written. Besides the HMI and the OPC-UA gateway
polling the plant, an implant on the gateway's host keeps a second connection
open and sends one FC3 read of one register at a fixed interval. The start
address of each read carries one character of a looping status message.

The student answers four questions: the implant's connection (client IP and
TCP port), its beacon interval, the message the addresses spell, and the
holding-register range a read allowlist must permit for the plant's real
readers. Grading is all or nothing (grade()'s default). The module does not
touch the stack.

The capture is generated by software/scripts/generate_covert_c2_pcap.py; the
values below are its answer key. tests/test_modbus_covert_c2.py regenerates
the capture, compares it with the committed file and derives these answers
from the bytes again, so they cannot drift.
"""
import re

from modules.defense_checks._answers import grade, number

IMPLANT_IP, IMPLANT_PORT = "172.18.0.5", 50918
INTERVAL_S = 5.0
MESSAGE = "gw ready for stage 2"
READ_RANGE = (1124, 1134)

LABELS = {
    "implant": "Client IP address and TCP port of the implant's connection",
    "interval": "Beacon interval",
    "message": "Message the implant's reads spell",
    "read_range": "Holding registers the legitimate readers need",
}


def connection(ip, port):
    """Accept 172.18.0.5:50918, '172.18.0.5 50918', '172.18.0.5, port 50918'."""
    def check(value):
        m = re.fullmatch(r"\s*(\d{1,3}(?:\.\d{1,3}){3})\s*(?:[:,/ ]|\s)\s*(?:port\s*)?(\d{1,5})\s*",
                         str(value), re.IGNORECASE)
        if not m:
            return False
        got_ip = ".".join(str(int(octet)) for octet in m.group(1).split("."))
        return got_ip == ip and int(m.group(2)) == port
    return check


def seconds(expected, tolerance):
    """Accept '5', '5.0 s', '5 seconds' or '5000 ms'."""
    def check(value):
        m = re.fullmatch(r"\s*([0-9]+(?:[.,][0-9]+)?)\s*(ms|milliseconds?|s|sec|seconds?)?\s*",
                         str(value), re.IGNORECASE)
        if not m:
            return False
        got = float(m.group(1).replace(",", "."))
        if (m.group(2) or "").lower().startswith("m"):
            got /= 1000.0
        return number(expected, tolerance)(str(got))
    return check


def text(expected):
    """Compare letters and digits only, case-insensitive (spacing and the separator do not count)."""
    want = re.sub(r"[^0-9a-z]", "", expected.casefold())

    def check(value):
        return re.sub(r"[^0-9a-z]", "", str(value).casefold()) == want
    return check


def register_range(first, last):
    """Accept '1124-1134', '1124..1134', '1124 to 1134', 'HR 1124 - 1134'."""
    def check(value):
        m = re.fullmatch(r"\s*(?:hr\s*)?(\d{1,5})\s*(?:-|–|\.\.|to)\s*(?:hr\s*)?(\d{1,5})\s*",
                         str(value), re.IGNORECASE)
        return bool(m) and (int(m.group(1)), int(m.group(2))) == (first, last)
    return check


def verify(answers=None):
    return grade(answers, {
        "implant": connection(IMPLANT_IP, IMPLANT_PORT),
        "interval": seconds(INTERVAL_S, 0.05),
        "message": text(MESSAGE),
        "read_range": register_range(*READ_RANGE),
    }, labels=LABELS,
        success_message="You heard the whisper. Reads look harmless, but an allowlist of "
                        "who may read which registers is what makes this one loud.",
        failure_message="At least one answer does not match the capture yet.")
