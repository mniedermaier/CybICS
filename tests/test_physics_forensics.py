def test_generator_tick_is_the_hwio_tick(generator):
    """Run the real simulation block of physical_process_thread() and the generator's
    copy from the same states with the same seeds: same pressures, same blow-out
    sensor, same number of random draws."""
    with open(HWIO, encoding="utf-8") as f:
        src = f.read()
    start = src.index("    if delay > 50:", src.index("def physical_process_thread"))
    end = src.index("    # Write to OpenPLC", start)
    block = compile(textwrap.dedent(src[start:end]), "hwio-tick", "exec")

    states = random.Random(1)
    for n in range(4000):
        state = {"gst": states.randint(0, 255), "hpt": states.randint(0, 255),
                 "boSen": states.randint(0, 1)}
        coils = {"compressor": states.randint(0, 1), "systemValve": states.randint(0, 1),
                 "gstSig": states.randint(0, 1)}
        real_rng, copy_rng = random.Random(n), random.Random(n)
        env = {**state, **coils, "sysSen": 0, "heartbeat": 0, "delay": 51, "timer": 0,
               "random": real_rng}
        exec(block, env)
        got = generator.plant_tick(state, coils, copy_rng)
        assert got == {"gst": env["gst"], "hpt": env["hpt"], "boSen": env["boSen"]}, (state, coils)
        assert real_rng.random() == copy_rng.random(), f"random draws differ for {state} {coils}"


def test_generator_plc_matches_cybics_st(generator):
    with open(PLC_PROGRAM, encoding="utf-8") as f:
        st = re.sub(r"\s+", " ", f.read())
    for clause in ("IF gst < 60 AND gstState = 0 THEN", "ELSIF gst < 240 AND gstState = 1 THEN",
                   "IF hpt < 60 AND compressorState = 0 AND gst > 50 THEN",
                   "ELSIF hpt < 90 AND compressorState = 1 AND gst > 50 THEN",
                   "IF hpt > 50 AND hpt<100 THEN", "IF stop < 1 THEN"):
        assert clause in st, f"cybICS.st changed ({clause}): update the generator's Plc"
    plc = generator.Plc()
    assert plc.scan(200, 59, 0) == {"compressor": 1, "systemValve": 1, "gstSig": 0}
    assert plc.scan(200, 89, 0)["compressor"] == 1
    assert plc.scan(200, 90, 0)["compressor"] == 0
    assert plc.scan(59, 70, 0)["gstSig"] == 1
    assert plc.scan(239, 70, 0)["gstSig"] == 1
    assert plc.scan(240, 70, 0)["gstSig"] == 0
    assert plc.scan(200, 30, 1) == {"compressor": 0, "systemValve": 0, "gstSig": 0}


def test_every_row_before_the_attack_obeys_the_plant(rows):
    found = analyse(committed())
    for i in range(1, found["first_index"]):
        assert not broken_rules(rows[i - 1], rows[i]), rows[i]["time"]
        assert not sensor_contradiction(rows[i]), rows[i]["time"]
    # Coils always follow the PLC's rules from the value the PLC saw.
    for r in rows:
        if r["stop"]:
            assert (r["compressor"], r["systemValve"], r["gstSig"]) == (0, 0, 0)
        else:
            assert r["systemValve"] == (1 if 50 < r["hpt"] < 100 else 0)


def test_the_decoys_are_in_the_file(rows):
    """The README warns about a frozen plant and refills during compressor runs."""
    stopped = [r for r in rows if r["stop"]]
    assert len(stopped) >= 200
    assert len({(r["gst"], r["hpt"]) for r in stopped}) == 1, "a stopped plant is frozen"
    overlap = [b for a, b in zip(rows, rows[1:]) if a["compressor"] and b["gst"] > a["gst"]]
    assert len(overlap) > 50, "GST rises while the compressor runs (refill)"
    # Normal compressor runs are much shorter than the one under attack.
    runs, n = [], 0
    for r in rows:
        if r["compressor"]:
            n += 1
        elif n:
            runs.append(n)
            n = 0
    assert max(runs) < 40 and n > 2 * max(runs)


def test_analysis_matches_module_and_key(built):
    _, key = built
    found = analyse(committed())
    assert found["first"] == check.FIRST_FORGED == key["first_forged"]
    assert found["true_hpt"] == check.TRUE_HPT_LAST_ROW == key["true_hpt_last_row"]
    assert found["shown_last"] == key["shown_hpt_last_row"]
    assert found["sensor_lie"] == key["first_sysSen_contradiction"]
    assert found["sensor_lie_index"] > found["first_index"] + 10, "sysSen must be a later, tempting answer"
    assert check.verify({"forged_value": found["forged"], "first_forged": found["first"],
                         "true_hpt": str(found["true_hpt"])})["success"]


