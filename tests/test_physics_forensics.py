# --- an independent analysis, as the README teaches it -----------------------

def broken_rules(prev, row):
    """The rules of the README's table that the step prev -> row breaks."""
    broken = []
    dh, dg = row["hpt"] - prev["hpt"], row["gst"] - prev["gst"]
    refill = range(0, 4) if prev["gstSig"] else range(0, 1)
    vent = (0, -1) if prev["boSen"] else (0,)
    if prev["compressor"]:
        if dh not in {1 + v for v in vent}:
            broken.append("hpt")
        if dg not in {-2 + r for r in refill}:
            broken.append("gst")
    else:
        use = (0, -1, -2) if prev["systemValve"] else (0,)
        if dh not in {u + v for u in use for v in vent}:
            broken.append("hpt")
        if dg not in set(refill):
            broken.append("gst")
    return broken


def sensor_contradiction(row):
    return row["stop"] == 0 and 50 < row["hpt"] < 100 and row["sysSen"] != row["systemValve"]


def analyse(text):
    """Derive the three answers from the export alone."""
    rows = parse(text)
    steps = [(i, broken_rules(rows[i - 1], rows[i])) for i in range(1, len(rows))]
    first = next(i for i, broken in steps if broken)
    # Every rule involving the GST holds all night; only the HPT breaks.
    assert all("gst" not in broken for _, broken in steps)
    assert all(set(broken) <= {"hpt"} for _, broken in steps)
    honest = rows[first - 1]
    tail = rows[first - 1:]
    assert all(r["gstSig"] == 0 and r["boSen"] == 0 and r["compressor"] == 1 for r in tail[:-1])
    true_last = honest["hpt"] + (honest["gst"] - rows[-1]["gst"]) // 2
    assert (honest["gst"] - rows[-1]["gst"]) % 2 == 0
    assert true_last - honest["hpt"] == len(tail) - 1, "gas balance and tick count disagree"
    lie = next(i for i, r in enumerate(rows) if sensor_contradiction(r))
    return {"forged": "hpt", "first": rows[first]["time"], "true_hpt": true_last,
            "first_index": first, "sensor_lie": rows[lie]["time"], "sensor_lie_index": lie,
            "shown_last": rows[-1]["hpt"], "rows": rows}


