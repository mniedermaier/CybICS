@pytest.mark.parametrize("answers,ok", [
    ({"forged_value": "hpt", "first_forged": "02:19:22", "true_hpt": "147"}, True),
    ({"forged_value": "HR 1126", "first_forged": "2026-03-21 02:19:22.6", "true_hpt": "147"}, True),
    ({"forged_value": "High-pressure tank", "first_forged": "2026-03-21T02:19:22.6", "true_hpt": "0x93"}, True),
    ({"forged_value": "HPT (HR1126, %MW102)", "first_forged": "02:19:22.6", "true_hpt": "147"}, True),
    ({"forged_value": "pressure", "first_forged": "02:19:22", "true_hpt": "147"}, False),
    ({"forged_value": "hpt and gst", "first_forged": "02:19:22", "true_hpt": "147"}, False),
    # the sysSen contradiction is later than the start
    ({"forged_value": "hpt", "first_forged": "02:20:03", "true_hpt": "147"}, False),
    # the last trusted row is not forged
    ({"forged_value": "hpt", "first_forged": "02:19:21", "true_hpt": "147"}, False),
    ({"forged_value": "hpt", "first_forged": "02:19:22.5", "true_hpt": "147"}, False),
    # what the screen showed, the forgotten 2:1 rate, an off-by-one start
    ({"forged_value": "hpt", "first_forged": "02:19:22", "true_hpt": "82"}, False),
    ({"forged_value": "hpt", "first_forged": "02:19:22", "true_hpt": "232"}, False),
    ({"forged_value": "hpt", "first_forged": "02:19:22", "true_hpt": "148"}, False),
    ({"forged_value": "gst", "first_forged": "02:19:22", "true_hpt": "147"}, False),
    ({"forged_value": "hpt, gst", "first_forged": "02:19:22", "true_hpt": "147"}, False),
    ({"forged_value": "sysSen", "first_forged": "02:19:22", "true_hpt": "147"}, False),
])
def test_grading(answers, ok):
    result = check.verify(answers)
    assert result["success"] is ok
    assert len(result["checks"]) == 1, "all or nothing"
    assert "147" not in json.dumps(result) and "02:19" not in json.dumps(result)


def test_config_entry():
    with open(CTF_CONFIG, encoding="utf-8") as f:
        config = json.load(f)
    entry = next(c for cat in config["categories"].values() for c in cat["challenges"]
                 if c["id"] == "physics_forensics")
    assert entry["type"] == "verify" and entry["verify_module"] == "check_physics_forensics"
    assert {a["name"] for a in entry["answers"]} == set(check.LABELS)
    assert re.fullmatch(r"CybICS\([A-Za-z0-9_]+\)", entry["flag"])
    assert "O" not in entry["flag"][6:] and "0" not in entry["flag"], "no 0/O ambiguity"
    assert entry["training_content"] == "training/physics_forensics/README.md"
    blob = json.dumps(entry)
    assert "147" not in blob and "02:19" not in blob
