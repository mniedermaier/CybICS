# --- a small, independent pcap reader ----------------------------------------

def requests_by_connection(data):
    """{(client ip, client port): [(time, fc, start, quantity)]} for Modbus requests to the PLC."""
    magic, _, _, _, _, _, linktype = struct.unpack("<IHHiIII", data[:24])
    assert magic == 0xA1B2C3D4 and linktype == 1
    conns, pos = {}, 24
    while pos < len(data):
        sec, usec, incl, _ = struct.unpack("<IIII", data[pos:pos + 16])
        raw = data[pos + 16:pos + 16 + incl]
        pos += 16 + incl
        assert raw[12:14] == b"\x08\x00" and raw[23] == 6
        ihl = (raw[14] & 0x0F) * 4
        total = struct.unpack("!H", raw[16:18])[0]
        t = 14 + ihl
        sport, dport = struct.unpack("!HH", raw[t:t + 4])
        payload = raw[t + (raw[t + 12] >> 4) * 4:14 + total]
        dst = ".".join(str(b) for b in raw[30:34])
        if dport != 502 or dst != PLC_IP or not payload:
            continue
        tid, proto, length, unit, fc = struct.unpack("!HHHBB", payload[:8])
        assert proto == 0 and length == len(payload) - 6 and unit == 1
        start, quantity = struct.unpack("!HH", payload[8:12])
        src = ".".join(str(b) for b in raw[26:30])
        conns.setdefault((src, sport), []).append((sec + usec / 1e6, fc, start, quantity))
    return conns


def analyse(data):
    """Answer the four questions from the capture, following the README's steps."""
    conns = requests_by_connection(data)
    profiles = {}
    for key, reqs in conns.items():
        reads = {(fc, start, qty) for _, fc, start, qty in reqs}
        # A poller asks for a small, fixed set again and again.
        profiles[key] = {"distinct": len(reads), "requests": len(reqs), "reads": reads}
    implant = max(profiles, key=lambda k: profiles[k]["distinct"] / profiles[k]["requests"])
    others = [k for k in conns if k != implant]

    times = [t for t, *_ in conns[implant]]
    gaps = [b - a for a, b in zip(times, times[1:])]
    interval = round(statistics.median(gaps), 3)

    decoded = "".join(chr(start & 0xFF) for _, _, start, _ in conns[implant])
    highs = {start >> 8 for _, _, start, _ in conns[implant]}
    separator = next(c for c in decoded if not (c.isalnum() or c == " "))
    message = max(decoded.split(separator), key=len)

    touched = set()
    for key in others:
        for _, fc, start, qty in conns[key]:
            if fc == 3:
                touched.update(range(start, start + qty))
    return {
        "conns": conns, "implant": implant, "others": others, "gaps": gaps,
        "interval": interval, "decoded": decoded, "highs": highs,
        "separator": separator, "message": message,
        "range": (min(touched), max(touched)), "touched": touched,
    }


