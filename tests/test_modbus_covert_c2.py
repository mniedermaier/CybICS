def test_only_reads_and_only_known_hosts(result):
    """The story: nothing was written, and no unknown IP address appears."""
    fcs = {fc for reqs in result["conns"].values() for _, fc, _, _ in reqs}
    assert fcs <= {1, 3}
    assert {ip for ip, _ in result["conns"]} == KNOWN_READERS


def test_the_implant_hides_behind_an_allowed_host(result):
    """A host allowlist cannot see it: it shares the gateway's address and function code."""
    implant_ip = result["implant"][0]
    assert implant_ip in KNOWN_READERS
    assert any(ip == implant_ip for ip, _ in result["others"])
    assert {fc for _, fc, _, _ in result["conns"][result["implant"]]} == {3}
    assert {qty for *_, qty in result["conns"][result["implant"]]} == {1}


def test_regular_timing_alone_does_not_single_out_the_implant(result):
    """Every connection is periodic; the README says rhythm confirms, it does not find."""
    for key in result["others"]:
        starts = [t for t, fc, start, _ in result["conns"][key]
                  if (fc, start) == result["conns"][key][0][1:3]]
        gaps = [b - a for a, b in zip(starts, starts[1:])]
        assert max(gaps) - min(gaps) < 0.01, key
    assert max(result["gaps"]) - min(result["gaps"]) < 0.001


def test_the_message_repeats_with_one_separator_and_one_high_byte(result):
    assert len(result["highs"]) == 1
    assert result["decoded"].count(result["message"]) >= 2
    assert not result["decoded"].startswith(result["message"]), "the recording starts mid-message"
    assert all(32 <= ord(c) < 127 for c in result["decoded"])


def test_the_implant_reads_words_no_one_else_uses(result):
    implant_words = {start for _, _, start, _ in result["conns"][result["implant"]]}
    assert not implant_words & result["touched"]


def test_the_legitimate_reads_match_the_fuxa_project_and_the_live_measurement(result):
    """FUXA's tags all sit in the FC3 block and the coils it reads (measured live on 2026-10-29)."""
    fuxa = [k for k in result["others"] if k[0] == "172.18.0.4"]
    assert len(fuxa) == 1
    shapes = {(fc, start, qty) for _, fc, start, qty in result["conns"][fuxa[0]]}
    assert shapes == {(3, 1124, 11), (1, 0, 4)}
    with open(os.path.join(ROOT, "software", "FUXA", "fuxa-project.json"), encoding="utf-8") as f:
        project = json.load(f)
    tags = []

    def walk(node):
        if isinstance(node, dict):
            if "memaddress" in node and str(node.get("address", "")).isdigit():
                tags.append((node["memaddress"], int(node["address"])))
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)
    walk(project)
    holding = {a - 1 for mem, a in tags if mem == "400000"}      # FUXA counts from 1
    coils = {a - 1 for mem, a in tags if mem == "000000"}
    assert holding and coils
    assert holding <= set(range(result["range"][0], result["range"][1] + 1))
    assert coils <= set(range(0, 4))


