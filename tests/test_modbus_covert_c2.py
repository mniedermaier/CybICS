# --- the allowlist tool -----------------------------------------------------------

def run_tool(tmp_path, rules):
    path = tmp_path / "rules.json"
    path.write_text(json.dumps(rules))
    out = subprocess.run([sys.executable, TOOL, PCAP, str(path)], capture_output=True,
                         text=True, check=True).stdout
    rows = {}
    for line in out.splitlines()[1:-1]:
        conn, passed, flagged = line.split()
        rows[conn] = (int(passed), int(flagged))
    return rows, out


def test_the_example_allowlist_flags_nothing(tmp_path):
    with open(os.path.join(FOLDER, "allowlist.example.json"), encoding="utf-8") as f:
        rows, _ = run_tool(tmp_path, json.load(f))
    assert all(flagged == 0 for _, flagged in rows.values())


def test_a_range_allowlist_flags_exactly_the_implant(tmp_path):
    first, last = check.READ_RANGE
    rows, out = run_tool(tmp_path, [
        {"client": "172.18.0.4", "fc": 3, "first": first, "last": last},
        {"client": "172.18.0.4", "fc": 1, "first": 0, "last": 3},
        {"client": "172.18.0.5", "fc": 3, "first": first, "last": last},
    ])
    implant = f"{check.IMPLANT_IP}:{check.IMPLANT_PORT}"
    for conn, (passed, flagged) in rows.items():
        if conn == implant:
            assert passed == 0 and flagged > 0
        else:
            assert flagged == 0, conn
    assert "gw" not in out and str(0x0500) not in out     # it never decodes for the student


def test_a_function_code_allowlist_still_misses_it(tmp_path):
    rows, _ = run_tool(tmp_path, [{"client": "172.18.0.4"}, {"client": "172.18.0.5", "fc": 3}])
    assert all(flagged == 0 for _, flagged in rows.values())


