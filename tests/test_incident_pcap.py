# --- the answers, from the bytes ------------------------------------------------

def test_the_capture_answers_the_four_questions_as_the_module_expects(result):
    assert result["rogue"] == check.ATTACKER_MAC
    assert result["ips"] == set(check.ATTACKER_IPS)
    assert result["poison"] == check.POISON_FRAME
    assert {n for n, *_ in result["stops"]} == set(check.STOP_FRAMES)


def test_the_generator_key_matches_the_module():
    _, key = load(GENERATOR, "generate_incident_pcap").build()
    assert key["attacker_mac"] == check.ATTACKER_MAC
    assert set(key["attacker_ips"]) == set(check.ATTACKER_IPS)
    assert key["poison_frame"] == check.POISON_FRAME
    assert set(key["stop_frames"]) == set(check.STOP_FRAMES)


def test_one_stop_per_protocol_each_from_the_rogue_card_under_a_different_address(result):
    stops = result["stops"]
    assert [proto for *_, proto, _ in stops] == ["modbus", "s7comm", "dnp3"]
    assert {src for _, _, src, _, _ in stops} == {result["rogue"]}
    assert [ip_src for *_, ip_src in stops] == ["172.18.0.4", "172.18.0.10", result["own_ip"]]


def test_the_operator_restarts_come_from_the_real_hmi_after_each_stop(result):
    runs, stops = result["runs"], result["stops"]
    assert len(runs) == 3 and {src for _, _, src in runs} == {FUXA_MAC}
    for (_, stop_time, *_), (_, run_time, _) in zip(stops, runs):
        assert stop_time < run_time
    # The decoy: a restart writes the same register from the same IP address.
    assert all(n not in check.STOP_FRAMES for n, _, _ in runs)


def test_the_plcs_answers_to_the_hmi_confirm_every_stop_and_restart(result):
    """README step 6: the fifth register of FUXA's poll (HR 1128) follows the stops."""
    stops = [when for _, when, *_ in result["stops"]]
    runs = [when for _, when, _ in result["runs"]]
    events = sorted([(t, 1) for t in stops] + [(t, 0) for t in runs])
    seen = 0
    for _, when, f in result["frames"]:
        p = f.get("payload", b"")
        if f.get("sport") == 502 and f.get("dport") == 42716 and len(p) == 31 and p[7] == 3:
            expected = 0
            for t, value in events:
                if t < when:
                    expected = value
            assert struct.unpack("!H", p[9 + 8:9 + 10])[0] == expected, when
            seen += 1
    assert seen >= 100


def test_the_poisoning_sends_the_plcs_answers_for_the_hmi_to_the_rogue(result):
    """README step 6: after the forged ARP reply the PLC delivers FUXA's answers to the Pi."""
    poison_time = next(when for n, when, _ in result["frames"] if n == result["poison"])
    to_hmi = [(when, f["dst"]) for _, when, f in result["frames"]
              if f.get("ip_src") == PLC_IP and f.get("ip_dst") == "172.18.0.4"]
    assert {dst for when, dst in to_hmi if when < poison_time} == {FUXA_MAC}
    assert {dst for when, dst in to_hmi if when > poison_time} == {result["rogue"]}


def test_wireshark_would_see_the_duplicate_address(result):
    """Before the poisoning the real owners show their MACs in ARP (Wireshark's duplicate check needs that)."""
    seen = {}
    for number, _, f in result["frames"]:
        if "spa" in f and number < result["poison"]:
            seen.setdefault(f["spa"], set()).add(f["sha"])
    assert seen["172.18.0.4"] == {FUXA_MAC}
    assert seen["172.18.0.10"] == {"02:42:ac:12:00:0a"}


# --- the protocol bytes are the stack's own ----------------------------------------

def test_the_dnp3_stop_is_the_frame_the_dnp3_side_door_script_sends():
    generator = load(GENERATOR, "generate_incident_pcap")
    dnp3 = load(DNP3_SCRIPT, "dnp3_stop")
    frame = dnp3.link_frame(dnp3.LINK_UNCONFIRMED_DATA, 10, 1,
                            dnp3.direct_operate_ao16(dnp3.STOP_INDEX, 1))
    assert frame == generator.DNP3_STOP


def test_the_s7_stop_writes_the_word_the_s7_side_door_names():
    generator = load(GENERATOR, "generate_incident_pcap")
    assert stop_value({"dport": 102, "payload": generator.S7_WRITE_STOP}) == ("s7comm", 1)


# --- grading ---------------------------------------------------------------------

RIGHT = {
    "attacker_mac": "b8:27:eb:3c:9a:71",
    "attacker_ips": "172.18.0.77, 172.18.0.4, 172.18.0.10",
    "poison_frame": "293",
    "stop_frames": "345, 553, 736",
}


@pytest.mark.parametrize("variant", [
    {},
    {"attacker_mac": "B8-27-EB-3C-9A-71"},
    {"attacker_mac": "b827.eb3c.9a71"},
    {"attacker_mac": "b827eb3c9a71"},
    {"attacker_ips": "172.18.0.10;172.18.0.4 172.18.0.77"},
    {"stop_frames": "736,345,#553"},
])
def test_right_answers_in_any_reasonable_spelling_pass(variant):
    result = check.verify({**RIGHT, **variant})
    assert result["success"], (variant, result)


@pytest.mark.parametrize("variant", [
    {"attacker_mac": "02:42:ac:12:00:04"},                       # the HMI, by its IP address
    {"attacker_mac": "RaspberryPiF_3c:9a:71"},                    # the vendor name is not the MAC
    {"attacker_ips": "172.18.0.77"},                              # only its own address
    {"attacker_ips": "172.18.0.77, 172.18.0.4"},                  # missed the workstation
    {"attacker_ips": "172.18.0.77, 172.18.0.4, 172.18.0.10, 172.18.0.3"},
    {"poison_frame": "294"},                                      # the second forged reply
    {"stop_frames": "345, 553"},                                  # missed the DNP3 stop
    {"stop_frames": "345, 469, 553, 736"},                        # an operator restart too
    {"stop_frames": "347, 554, 737"},                             # the PLC's replies
    {"stop_frames": "345, 345, 553, 736"},
])
def test_wrong_answers_fail_without_saying_which(variant):
    result = check.verify({**RIGHT, **variant})
    assert not result["success"], variant
    assert [c["name"] for c in result["checks"]] == ["Answers"]
    text = json.dumps(result)
    assert "293" not in text and "b8:27" not in text


def test_the_config_declares_exactly_the_graded_fields():
    with open(CTF_CONFIG, encoding="utf-8") as f:
        config = json.load(f)
    entry = next(c for cat in config["categories"].values() for c in cat["challenges"]
                 if c["id"] == "incident_pcap")
    assert entry["type"] == "verify" and entry["verify_module"] == "check_incident_pcap"
    assert [a["name"] for a in entry["answers"]] == list(check.LABELS)
    for field in entry["answers"]:
        assert len(RIGHT[field["name"]]) <= field["max_length"], field["name"]
    assert os.path.isfile(os.path.join(ROOT, entry["training_content"]))
    blob = json.dumps(entry)
    assert "b8:27" not in blob and "293" not in blob and "345" not in blob


def test_the_readme_solution_names_the_graded_answers():
    """The README's Solution quotes frame numbers; a regenerated capture must update it."""
    with open(os.path.join(ROOT, "training", "incident_pcap", "README.md"), encoding="utf-8") as f:
        solution = f.read().split("## Solution", 1)[1]
    assert check.ATTACKER_MAC in solution
    for ip_address in check.ATTACKER_IPS:
        assert ip_address in solution
    for number in [check.POISON_FRAME, *check.STOP_FRAMES]:
        assert f"**{number}**" in solution, number
