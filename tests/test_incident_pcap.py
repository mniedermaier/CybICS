STOP_REGISTER = 1128


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# --- a small, independent pcap reader ----------------------------------------

def mac(raw):
    return ":".join(f"{b:02x}" for b in raw)


def ip(raw):
    return ".".join(str(b) for b in raw)


def read_frames(data):
    """[(number, time, frame dict)] for an Ethernet pcap (microsecond, little-endian)."""
    magic, _, _, _, _, _, linktype = struct.unpack("<IHHiIII", data[:24])
    assert magic == 0xA1B2C3D4 and linktype == 1
    frames, pos, number = [], 24, 0
    while pos < len(data):
        sec, usec, incl, _ = struct.unpack("<IIII", data[pos:pos + 16])
        raw = data[pos + 16:pos + 16 + incl]
        pos += 16 + incl
        number += 1
        frame = {"dst": mac(raw[0:6]), "src": mac(raw[6:12]), "type": struct.unpack("!H", raw[12:14])[0]}
        if frame["type"] == 0x0806:
            op = struct.unpack("!H", raw[20:22])[0]
            frame.update(arp_op=op, sha=mac(raw[22:28]), spa=ip(raw[28:32]),
                         tha=mac(raw[32:38]), tpa=ip(raw[38:42]))
        elif frame["type"] == 0x0800:
            ihl = (raw[14] & 0x0F) * 4
            total = struct.unpack("!H", raw[16:18])[0]
            frame.update(ip_src=ip(raw[26:30]), ip_dst=ip(raw[30:34]), proto=raw[23])
            if raw[23] == 6:
                t = 14 + ihl
                sport, dport = struct.unpack("!HH", raw[t:t + 4])
                offset = (raw[t + 12] >> 4) * 4
                frame.update(sport=sport, dport=dport, flags=raw[t + 13],
                             payload=raw[t + offset:14 + total])
        frames.append((number, sec + usec / 1e6, frame))
    return frames


def stop_value(frame):
    """(protocol, value) if the frame is a request that writes the stop flag, else None."""
    p, port = frame.get("payload", b""), frame.get("dport")
    if port == 502 and len(p) >= 12 and p[7] == 6:
        register, value = struct.unpack("!HH", p[8:12])
        if register == STOP_REGISTER:
            return "modbus", value
    if port == 102 and len(p) > 25 and p[7] == 0x32 and p[8] == 1 and p[17] == 0x05:
        # TPKT(4) COTP(3) S7 header(10): param starts at 17; one Write Var item
        item = p[19:31]
        db, area = struct.unpack("!H", item[6:8])[0], item[8]
        byte_address = int.from_bytes(item[9:12], "big") >> 3
        data_len = struct.unpack("!H", p[33:35])[0] // 8
        value = int.from_bytes(p[35:35 + data_len], "big")
        if area == 0x84 and db == 1002 and byte_address == 208:
            return "s7comm", value
    if port == 20000 and len(p) >= 25 and p[:2] == b"\x05\x64":
        app = p[10:26]                       # first user block (CRC stripped)
        if app[2] == 0x05 and app[3:5] == bytes([41, 2]):   # Direct Operate, g41v2
            index, value = struct.unpack("<Hh", app[8:12])
            if index == STOP_REGISTER:
                return "dnp3", value
    return None


def analyse(data):
    """Answer the four questions from the capture, following the README's steps."""
    frames = read_frames(data)
    macs = {f["src"] for _, _, f in frames} | {f["dst"] for _, _, f in frames}
    unknown = sorted(macs - KNOWN_MACS)
    assert len(unknown) == 1, unknown
    rogue = unknown[0]

    own_ip = None
    claimed, used = set(), set()
    poison = None
    for number, _, f in frames:
        if f["src"] != rogue:
            continue
        if f.get("arp_op") == 1 and f["spa"] != "0.0.0.0":
            own_ip = own_ip or f["spa"]
        if f.get("arp_op") == 2:
            claimed.add(f["spa"])
            if poison is None and f["spa"] != own_ip:
                poison = number
        if "ip_src" in f:
            used.add(f["ip_src"])

    stops, runs = [], []
    for number, when, f in frames:
        hit = stop_value(f) if f.get("ip_dst") == PLC_IP else None
        if hit and hit[1]:
            stops.append((number, when, f["src"], hit[0], f["ip_src"]))
        elif hit:
            runs.append((number, when, f["src"]))
    return {
        "rogue": rogue, "own_ip": own_ip, "ips": used | claimed, "poison": poison,
        "stops": stops, "runs": runs, "frames": frames,
    }


