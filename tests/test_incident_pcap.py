"""The Incident PCAP challenge: its capture, its answers and its verify module, without a stack.

training/incident_pcap/incident.pcap is generated by
software/scripts/generate_incident_pcap.py. These tests

- regenerate it and require the committed file to be byte-identical, so the
  file is never edited by hand and the generator stays deterministic;
- read the committed file with an analysis written here, independent of the
  generator, the way the README asks a student to: find the unknown MAC,
  follow it, find its forged ARP replies and every write to the stop flag on
  Modbus, S7comm and DNP3. Its answers must equal the constants in
  check_incident_pcap.py and the generator's key, so the challenge is
  solvable from the bytes alone and the three cannot drift;
- check that the S7comm and DNP3 requests in the capture are what the
  stack's clients send (the DNP3 frame is rebuilt with the DNP3 Side Door's
  solution script) and that the PLC's own answers confirm each stop;
- grade the module with right and wrong answers.

tests/test_training.py::TestIncidentPcap downloads the capture from the
running landing page and solves the challenge there.
"""
